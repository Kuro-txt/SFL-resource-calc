// The reverse ID map
export const KNOWN_ITEMS = Object.assign(
  {},
  ...Object.entries(KNOWN_IDS).map(([name, id]) => ({ [id]: name }))
);

export function getItemNameById(id) {
  if (id === undefined || id === null) return 'Unknown Item';
  if (KNOWN_ITEMS[id]) return KNOWN_ITEMS[id];
  if (typeof id === 'string' && isNaN(Number(id))) return id;
  return `Item #${id}`;
}
